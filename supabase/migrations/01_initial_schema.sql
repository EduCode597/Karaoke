-- ========================================================
-- PINOYVIDEOKE - SUPABASE DATABASE MIGRATION 01
-- Target: PostgreSQL 15+ on Supabase Cloud
-- Description: Creates songs catalog, queue_items, full-text search, and RLS
-- ========================================================

-- 1. Create Songs Table
CREATE TABLE IF NOT EXISTS public.songs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(5) UNIQUE NOT NULL,
  title VARCHAR(255) NOT NULL,
  artist VARCHAR(255) NOT NULL,
  language VARCHAR(50) DEFAULT 'Tagalog',
  youtube_id VARCHAR(50) NOT NULL,
  lrc_content TEXT,
  key_offset INT DEFAULT 0,
  duration INT DEFAULT 0,
  -- PostgreSQL Full-Text Search tsvector column (auto-computed from title and artist)
  search_tokens tsvector GENERATED ALWAYS AS (
    to_tsvector('english', coalesce(title, '') || ' ' || coalesce(artist, ''))
  ) STORED,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Performance Indexes
CREATE INDEX IF NOT EXISTS songs_code_idx ON public.songs(code);
CREATE INDEX IF NOT EXISTS songs_search_idx ON public.songs USING GIN(search_tokens);
CREATE INDEX IF NOT EXISTS songs_language_idx ON public.songs(language);

-- 3. Create Queue Items Table
CREATE TABLE IF NOT EXISTS public.queue_items (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  room_code VARCHAR(10) NOT NULL,
  song_id BIGINT REFERENCES public.songs(id) ON DELETE CASCADE,
  singer_name VARCHAR(100) DEFAULT 'Guest',
  position INT NOT NULL DEFAULT 1,
  status VARCHAR(20) DEFAULT 'queued', -- 'queued' | 'playing' | 'completed' | 'skipped'
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Queue Indexes
CREATE INDEX IF NOT EXISTS queue_room_idx ON public.queue_items(room_code, position);

-- 5. Enable Row Level Security (RLS)
ALTER TABLE public.songs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.queue_items ENABLE ROW LEVEL SECURITY;

-- 6. RLS Policies
-- Songs: Public can view all songs in the songbook
DROP POLICY IF EXISTS "Public can view songs" ON public.songs;
CREATE POLICY "Public can view songs" ON public.songs
  FOR SELECT USING (true);

-- Queue Items: Anyone can read, insert, update, or delete items within any room
DROP POLICY IF EXISTS "Public can read and modify queue" ON public.queue_items;
CREATE POLICY "Public can read and modify queue" ON public.queue_items
  FOR ALL USING (true) WITH CHECK (true);

-- 7. Enable Realtime Replication for queue_items table
-- This allows clients to listen to live INSERT, UPDATE, DELETE changes
ALTER PUBLICATION supabase_realtime ADD TABLE public.queue_items;
